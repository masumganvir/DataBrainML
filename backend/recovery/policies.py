    INFO = "INFO"
    WARNING = "WARNING"
    RECOVERABLE = "RECOVERABLE"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"
    SECURITY_CRITICAL = "SECURITY_CRITICAL"

