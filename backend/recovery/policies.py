# Categories that are safe for automatic exponential-backoff retries
RETRYABLE_CATEGORIES: Set[ErrorCategory] = {
    ErrorCategory.TRANSIENT,
    ErrorCategory.RATE_LIMIT,
    ErrorCategory.NETWORK,
    ErrorCategory.TIMEOUT,
    ErrorCategory.LLM_TIMEOUT,
    ErrorCategory.STREAM_FAILURE,
}

# Categories requiring pipeline strategy modification rather than blind retries
ADAPTIVE_RECOVERY_CATEGORIES: Set[ErrorCategory] = {
    ErrorCategory.DATA_FORMAT,
    ErrorCategory.DATA_QUALITY,
    ErrorCategory.MISSING_VALUE,
    ErrorCategory.FEATURE_ENGINEERING,
    ErrorCategory.MODEL_TRAINING,
    ErrorCategory.MODEL_SERIALIZATION,
    ErrorCategory.RESOURCE_EXHAUSTION,
    ErrorCategory.MEMORY,
    ErrorCategory.LLM_PROVIDER,
    ErrorCategory.LLM_QUOTA,
    ErrorCategory.MCP_FAILURE,
}

# Categories strictly demanding immediate security stop
SECURITY_HALT_CATEGORIES: Set[ErrorCategory] = {
    ErrorCategory.SECURITY,
    ErrorCategory.AUTHENTICATION,
    ErrorCategory.AUTHORIZATION,
}
