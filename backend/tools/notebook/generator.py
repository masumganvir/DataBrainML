    sns.heatmap(corr, annot=True, fmt='.2f', cmap='coolwarm', vmin=-1, vmax=1, linewidths=0.5)
    plt.title("Pearson Correlation Matrix", fontsize=13, fontweight='bold')
    plt.tight_layout()
    plt.show()
